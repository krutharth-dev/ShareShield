import { createHash } from 'node:crypto'
import { expect, test, type Page } from '@playwright/test'

async function noOverflow(page: Page) {
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
}

test('fictional text can be reviewed and downloaded', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await noOverflow(page)
  await page.getByRole('button', { name: 'Use fictional sample', exact: true }).click()
  await page.getByRole('button', { name: 'Analyze document' }).click()
  await page.getByRole('button', { name: 'Generate & verify' }).click()
  await expect(page.getByRole('heading', { name: 'Verification: UNVERIFIED' })).toBeVisible()
  const download = page.getByRole('button', { name: 'Download reviewed copy' })
  await expect(download).toBeDisabled()
  await page.getByRole('checkbox', { name: 'I have inspected the export' }).check()
  const receipt = page.waitForEvent('download')
  await download.click()
  const file = await receipt
  expect(await file.failure()).toBeNull()
  const stream = await file.createReadStream()
  const chunks: Buffer[] = []
  for await (const chunk of stream!) chunks.push(Buffer.from(chunk))
  const content = Buffer.concat(chunks).toString()
  expect(content).not.toContain('demo@example.org')
  expect(content).toContain('[REDACTED]')
  expect(content).toContain('HDFC0001234')
  await expect(page.locator('.report-digest')).toContainText(createHash('sha256').update(Buffer.concat(chunks)).digest('hex'))
  await noOverflow(page)
  expect(errors).toEqual([])
})

test('preview supports browsing, deliberate masks, cancellation and undo/redo', async ({ page, browserName, isMobile }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Use fictional ID image', exact: true }).click()
  await page.getByRole('button', { name: 'Analyze document' }).click()
  const frame = page.locator('.page-frame').first()
  await expect(frame.locator('img')).toBeVisible()
  await noOverflow(page)
  await page.getByRole('slider', { name: 'Zoom' }).fill('200')
  const draw = page.getByRole('button', { name: 'Draw mask', exact: true })
  await expect(draw).toHaveAttribute('aria-pressed', 'false')
  await expect(frame).toHaveCSS('touch-action', 'auto')
  await draw.click()
  await expect(page.getByRole('button', { name: 'Original focus', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expect(frame).toHaveCSS('touch-action', 'none')
  await frame.scrollIntoViewIfNeeded()
  const rect = await frame.boundingBox()
  if (!rect) throw Error('Preview missing')
  await page.mouse.move(rect.x + rect.width * .1, rect.y + rect.height * .1)
  await page.mouse.down()
  await page.mouse.move(rect.x + rect.width * .4, rect.y + rect.height * .3, { steps: 5 })
  await page.mouse.up()
  await expect(page.locator('.manual-mask')).toHaveCount(1)
  const mask = page.locator('.manual-mask')
  expect(Number(await mask.getAttribute('width'))).toBeCloseTo(300, -1)
  expect(Number(await mask.getAttribute('height'))).toBeCloseTo(200, -1)
  await page.getByRole('button', { name: 'Undo edit', exact: true }).click()
  await expect(page.locator('.manual-mask')).toHaveCount(0)
  await page.getByRole('button', { name: 'Redo edit', exact: true }).click()
  await expect(page.locator('.manual-mask')).toHaveCount(1)
  // Non-primary contacts cannot start a mask or finish another finger's stroke.
  await frame.dispatchEvent('pointerdown', { pointerId: 22, pointerType: 'touch', isPrimary: false, button: 0, clientX: rect.x + 20, clientY: rect.y + 20 })
  await frame.dispatchEvent('pointerup', { pointerId: 22, pointerType: 'touch', isPrimary: false, clientX: rect.x + 100, clientY: rect.y + 100 })
  await expect(page.locator('.manual-mask')).toHaveCount(1)
  await frame.scrollIntoViewIfNeeded()
  const current = await frame.boundingBox()
  if (!current) throw Error('Preview missing')
  await page.mouse.move(current.x + 10, current.y + 10)
  await page.mouse.down()
  await frame.dispatchEvent('pointercancel', { pointerId: 1, pointerType: 'mouse', isPrimary: true })
  await page.mouse.up()
  await expect(page.locator('.manual-mask')).toHaveCount(1)
  await page.getByRole('button', { name: 'Drawing masks', exact: true }).click()
  await expect(frame).toHaveCSS('touch-action', 'auto')
  if (browserName === 'chromium' && isMobile) {
    const viewport = page.locator('.zoom-viewport').first()
    await viewport.scrollIntoViewIfNeeded()
    await viewport.evaluate(element => { element.scrollLeft = 0 })
    const visible = await viewport.boundingBox()
    if (!visible) throw Error('Scroll viewport missing')
    const height = page.viewportSize()!.height
    const y = (Math.max(0, visible.y) + Math.min(height, visible.y + visible.height)) / 2
    const cdp = await page.context().newCDPSession(page)
    await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: visible.x + visible.width * .8, y }] })
    for (let step = 1; step <= 10; step++) {
      await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: visible.x + visible.width * (.8 - .06 * step), y }] })
      await page.waitForTimeout(20)
    }
    await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
    await expect.poll(() => viewport.evaluate(element => element.scrollLeft)).toBeGreaterThan(20)
    await expect(page.locator('.manual-mask')).toHaveCount(1)
    await cdp.detach()
  }
  await page.getByRole('button', { name: 'Generate & verify' }).click()
  await expect(page.getByRole('heading', { name: 'Verification: UNVERIFIED' })).toBeVisible()
  const download = page.getByRole('button', { name: 'Download reviewed copy' })
  await expect(download).toBeDisabled()
  await page.getByRole('checkbox', { name: 'I have inspected the export' }).check()
  await expect(download).toBeDisabled()
  await page.getByRole('checkbox', { name: 'I have visually checked page 1' }).check()
  await expect(download).toBeEnabled()
  const receipt = page.waitForEvent('download')
  await download.click()
  expect(await (await receipt).failure()).toBeNull()
  await noOverflow(page)
})

test('category changes preserve individual choices in other categories', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Use fictional ID image', exact: true }).click()
  await page.getByRole('button', { name: 'Analyze document' }).click()
  const phone = page.getByRole('checkbox', { name: /98765 43210 indian mobile/ })
  const suggestion = page.getByRole('checkbox', { name: /2345 6789 0123 id12/ })
  await phone.uncheck()
  await suggestion.check()
  await page.getByRole('checkbox', { name: /Bank accounts, PAN, UPI & cards Payment/ }).uncheck()
  await expect(phone).not.toBeChecked()
  await expect(suggestion).toBeChecked()
  // Changing the category itself still applies its automatic defaults.
  await page.getByRole('checkbox', { name: /Phone and email Email/ }).uncheck()
  await page.getByRole('checkbox', { name: /Phone and email Email/ }).check()
  await expect(phone).toBeChecked()
  await expect(suggestion).toBeChecked()
})

test('manual editing restores the original after export focus and exports the drawn box', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Use fictional ID image', exact: true }).click()
  await page.getByRole('button', { name: 'Analyze document' }).click()
  await page.getByRole('button', { name: 'Generate & verify' }).click()
  await expect(page.getByRole('heading', { name: 'Verification: UNVERIFIED' })).toBeVisible()
  await page.getByRole('button', { name: 'Export focus', exact: true }).click()
  await expect(page.getByRole('img', { name: 'Original page 1', exact: true })).toBeHidden()
  await page.getByRole('button', { name: 'Draw mask', exact: true }).click()
  const original = page.getByRole('img', { name: 'Original page 1', exact: true })
  await expect(original).toBeVisible()
  await original.scrollIntoViewIfNeeded()
  const rect = await original.boundingBox()
  if (!rect) throw Error('Original preview missing')
  await page.mouse.move(rect.x + rect.width * .1, rect.y + rect.height * .1)
  await page.mouse.down()
  await page.mouse.move(rect.x + rect.width * .3, rect.y + rect.height * .2, { steps: 5 })
  await page.mouse.up()
  await expect(page.locator('.manual-mask')).toHaveCount(1)
  await expect(original).toBeVisible()
  const exportRequest = page.waitForRequest(request => request.url().endsWith('/redact'))
  // Keep a request in flight long enough to exercise controls outside the
  // review fieldset as well as the disabled fieldset itself.
  let releaseExport!: () => void
  const exportGate = new Promise<void>(resolve => { releaseExport = resolve })
  await page.route('**/redact', async route => { await exportGate; await route.continue() })
  await page.getByRole('button', { name: 'Generate & verify' }).click()
  expect((await exportRequest).postData()).toContain('manual_regions')
  await page.locator('.advanced-settings > summary').click()
  await expect(page.getByRole('checkbox', { name: /Protect every recognized occurrence/ })).toBeDisabled()
  releaseExport()
  await expect(page.getByRole('heading', { name: 'Verification: UNVERIFIED' })).toBeVisible()
  await expect(page.locator('.report-card')).toContainText('1 manual masks')
  await page.getByRole('button', { name: 'Export focus', exact: true }).click()
  await page.getByRole('button', { name: 'Move →', exact: true }).click()
  await expect(original).toBeVisible()
  await expect(page.getByRole('button', { name: 'Export focus', exact: true })).toBeDisabled()
  await expect(page.getByRole('button', { name: 'Original focus', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await noOverflow(page)
})

test('real touchscreen gestures draw a normalized mask', async ({ page, browserName, isMobile }) => {
  test.skip(browserName !== 'chromium' || !isMobile, 'CDP touchscreen input requires mobile Chromium')
  await page.goto('/')
  await page.getByRole('button', { name: 'Use fictional ID image', exact: true }).click()
  await page.getByRole('button', { name: 'Analyze document' }).click()
  await page.getByRole('button', { name: 'Draw mask', exact: true }).click()
  const original = page.getByRole('img', { name: 'Original page 1', exact: true })
  await expect(original).toBeVisible()
  await original.scrollIntoViewIfNeeded()
  const rect = await original.boundingBox()
  if (!rect) throw Error('Original preview missing')
  const cdp = await page.context().newCDPSession(page)
  const x = rect.x + rect.width * .1
  const y = rect.y + rect.height * .1
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x, y }] })
  for (let step = 1; step <= 5; step++) {
    await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: x + rect.width * .04 * step, y: y + rect.height * .02 * step }] })
  }
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
  await expect(page.locator('.manual-mask')).toHaveCount(1)
  expect(Number(await page.locator('.manual-mask').getAttribute('width'))).toBeCloseTo(200, -1)
  expect(Number(await page.locator('.manual-mask').getAttribute('height'))).toBeCloseTo(100, -1)
  await cdp.detach()
})
