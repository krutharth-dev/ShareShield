import { expect, test } from '@playwright/test'

test('manual rectangle editor opens before any automatic scan', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Use fictional ID image', exact: true }).click()
  const response = page.waitForResponse('**/analyze')
  await page.getByRole('button', { name: 'Open manual editor', exact: true }).click()
  expect(await (await response).json()).toMatchObject({ manual_only: true, findings: [] })
  await expect(page.getByRole('button', { name: 'Drawing masks', exact: true })).toHaveAttribute('aria-pressed', 'true')
  const image = page.getByRole('img', { name: 'Original page 1', exact: true })
  await expect.poll(() => image.evaluate(element => (element as HTMLImageElement).complete && (element as HTMLImageElement).naturalWidth > 0)).toBe(true)
  await image.scrollIntoViewIfNeeded()
  const rect = await image.boundingBox()
  if (!rect) throw Error('Manual preview missing')
  await page.mouse.move(rect.x + rect.width * .1, rect.y + rect.height * .2)
  await page.mouse.down()
  await page.mouse.move(rect.x + rect.width * .4, rect.y + rect.height * .35, { steps: 5 })
  await page.mouse.up()
  await expect(page.locator('.manual-mask')).toHaveCount(1)
  await expect(page.locator('.auto-mask')).toHaveCount(0)
})

test('manual text editor redacts an undetected phrase and downloads the result', async ({ page }) => {
  await page.goto('/')
  await page.locator('input[type=file]').setInputFiles({ name: 'fictional.txt', mimeType: 'text/plain', buffer: Buffer.from('Redwood Project\nKeep this public sentence\n') })
  await page.getByRole('button', { name: 'Open manual editor', exact: true }).click()
  await expect(page.getByRole('toolbar', { name: 'Manual text selection tools' })).toBeVisible()
  await page.getByRole('textbox', { name: 'Exact text to redact' }).fill('Redwood Project')
  await page.getByRole('button', { name: 'Add matching text', exact: true }).click()
  await expect(page.getByLabel('Selected manual text')).toContainText('1 manual text selections')
  await page.getByRole('button', { name: 'Generate & verify' }).click()
  await expect(page.locator('.report-card')).toContainText('1 manual text selections')
  await page.getByRole('checkbox', { name: 'I have inspected the export' }).check()
  const receipt = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Download reviewed copy' }).click()
  const stream = await (await receipt).createReadStream()
  const parts: Buffer[] = []
  for await (const part of stream!) parts.push(Buffer.from(part))
  const text = Buffer.concat(parts).toString()
  expect(text).toContain('[REDACTED]')
  expect(text).not.toContain('Redwood Project')
  expect(text).toContain('Keep this public sentence')
})

test('native text highlighting can be added as a manual selection', async ({ page }) => {
  await page.goto('/')
  await page.locator('input[type=file]').setInputFiles({ name: 'fictional.txt', mimeType: 'text/plain', buffer: Buffer.from('Redwood Project\nPublic sentence\n') })
  await page.getByRole('button', { name: 'Open manual editor', exact: true }).click()
  const text = page.locator('pre[data-text-location="plain-text"]')
  await expect(text).toBeVisible()
  await text.scrollIntoViewIfNeeded()
  const rect = await text.boundingBox()
  if (!rect) throw Error('Text preview missing')
  await page.mouse.dblclick(rect.x + 30, rect.y + 12)
  const add = page.getByRole('button', { name: 'Redact selected text', exact: true })
  await expect(add).toBeEnabled()
  await add.click()
  await expect(page.getByLabel('Selected manual text')).toContainText('Redwood')
  await expect(page.getByRole('button', { name: 'Generate & verify' })).toBeEnabled()
})
